# -*- coding: utf-8 -*-
"""说明书补【十七】：队员完善资料（名册收集+照片）、赛事名匹配、成绩榜改版"""
import io, os

HERE = os.path.dirname(os.path.abspath(__file__))
SEC = u"""


════════════════════════════════════════════════════════════════════
【十七】队员完善资料（名册收集 + 个人照片）· 赛事名匹配 · 成绩榜改版
════════════════════════════════════════════════════════════════════

★ 队员端：https://zl4639574-bit.github.io/maitian-running/report/ 里有两个页签
    · 成绩上报（见【十四】）
    · 完善我的资料（队员自己填，不用登录）：

  · 填：姓名、性别、学院、专业、年级；
  · 最好成绩：800 米 / 1500 米 / 3000 米 / 5000 米 / 10000 米 / 半马 / 全马，
    跑过的填最好一次（18:35、1:23:29 都行），没跑过的那一项点旁边的「无」；
  · 个人照片（可选）：点一下选照片，会自动压小；没上传的，名册里先用队徽显示；
  · 交给队长：点「复制资料文本」发文字，或点「导出资料文件（含照片）」——
    .json 小文件连照片一起打包，队长选这个文件就能一次导入。

★ 队长端：数据管理 → 队员名册 →「＋ 导入队员资料（队员发来的文件）」
    · 选队员发来的 .json 文件，或把队员发来的文字粘到下面的框里 → 点「解析这段文字」；
    · 会先显示这份资料的内容（姓名在不在名册、哪几项成绩、有没有照片），确认无误再点「导入这份资料」；
    · 导入后：性别/学院/专业/年级写进名册；非「无」的成绩进个人最好成绩榜；
      照片上传成头像（没配令牌时会先存在本机，配好令牌重新导入即可）；
    · 最后照旧点「同步我的修改到线上」，展示版名册就会显示头像。

★ 赛事名会自动对到已有赛事（队员上报时）
    · 在「赛事名称」框里打几个字，下面会提示「≈ 最像已有赛事：2025年杨凌农科城马拉松赛 — 用这个」；
    · 点「用这个」= 并进那一场；不点，就算新赛事（队长那边会新建这一场）。

★ 成绩榜现在以「个人最好成绩」为主
    · 打开成绩榜默认就是个人最好成绩；想按比赛看，点上面的「赛事成绩 N」→ 列出全部场次，
      点任意一场看那场的完整成绩册（名次按成绩排），页面上有「← 赛事列表」返回。
"""
for fn in ('使用说明.txt', 'guide.txt'):
    p = os.path.join(HERE, fn)
    s = io.open(p, encoding='utf-8-sig').read()
    if u'【十七】' in s:
        print(fn, '已写过，跳过')
        continue
    io.open(p, 'w', encoding='utf-8-sig', newline='').write(s.rstrip() + SEC.replace('\n', '\r\n'))
    print(fn, '已追加【十七】')
