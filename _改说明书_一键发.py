# -*- coding: utf-8 -*-
"""说明书补【十八】：一键发给队长（不用复制）+ 想"真正自动入库"的三条路"""
import io, os

HERE = os.path.dirname(os.path.abspath(__file__))
SEC = u"""


════════════════════════════════════════════════════════════════════
【十八】队员不用复制，一键发给队长（📤）· 以及"真正自动入库"怎么做
════════════════════════════════════════════════════════════════════

★ 队员端：「成绩上报」和「完善我的资料」两个页签都有一个
    「📤 直接发给队长」按钮：
      · 点一下会打开手机的系统分享面板（安卓 Chrome / 苹果 Safari 都支持）；
      · 选「微信」→ 选队长或队群 → 发送，就把成绩 / 资料（连照片）发过去了，
        全程不用复制粘贴、不用截图；
      · 如果这个浏览器不支持分享，会自动退回复制，粘一下就行（会提示已复制）。

★ 队长端：队长版 →「上传成绩」→「② 接收上报（成绩 / 资料都能贴）」
      · 把队员发来的文字粘进去，或把文件里的内容粘进去 → 点「解析并预览」；
      · 会自动分辨：是成绩就列成成绩清单（还会标出谁是队员/非队员），
        是资料就显示「姓名 / 信息 / 最好成绩 / 有没有照片」→ 确认后一键导入。

★ 想做到"队员点一下就进你后台、连微信都不用发"——需要一台中转服务器。三条路：
    ① 问卷星 / 腾讯文档（或飞书多维表）收集表：国内可达、免费、不用实名，
       队员点一下真的就提交到你后台了；缺点：数据不自动进网页，
       你要导出 Excel，再用「上传成绩 → 批量导入 Excel」导进来（和现有流程兼容）。
    ② 自建中转（腾讯云函数 / 云开发）：能做到"点一下就写进仓库"，但要实名 + 一点运维。
    ③ 给每个队员发写入令牌：不推荐 —— 令牌就是写权限，泄露了会被人刷垃圾甚至删数据。
    （Cloudflare Workers、Vercel、Supabase、Firebase 这些国内打不开，已排除。）

    结论：日常用「📤 一键发」最省事（队员零复制、你不用维护服务器）；
          要"完全不经过微信"，就用 ① 的收集表，我可以给你写好问题清单和导出-导入的对应关系。
"""
for fn in ('使用说明.txt', 'guide.txt'):
    p = os.path.join(HERE, fn)
    s = io.open(p, encoding='utf-8-sig').read()
    if u'【十八】' in s:
        print(fn, '已写过，跳过')
        continue
    io.open(p, 'w', encoding='utf-8-sig', newline='').write(s.rstrip() + SEC.replace('\n', '\r\n'))
    print(fn, '已追加【十八】')
