# -*- coding: utf-8 -*-
"""说明书补一节：整场成绩单（含非队员）怎么导"""
import io, os

HERE = os.path.dirname(os.path.abspath(__file__))
SEC = u"""


════════════════════════════════════════════════════════════════════
【十三】整场成绩单（含非队员、外校选手）怎么导进来
════════════════════════════════════════════════════════════════════

  场景：一次比赛或测速有一份完整成绩单（比如计时公司发来的表），里面既有队员也有非队员。

  做法：队长版 →「上传成绩」→「② 批量导入 Excel / CSV」→ 把文件拖进去（手机点一下选文件）：
    · 确认「姓名列 / 成绩列 / 名次列 / 性别列 / 学院列」挑得对不对 → 点「导入这 N 行」；
    · 预览里会标出每个人是「队员」还是「非队员」：非队员照样导入，
      但只出现在这场比赛的榜上，不会进名册、也不会进个人最好成绩榜；
    · 成绩能认这些写法：17:35、1:23:29、18'35"、18.5（分钟）、
      Excel 里存成时间格式的（单元格显示 17:35，实际是 0.7326）、直接写秒数的（1022 = 17:02）；
    · 姓名支持 2~14 个字符：中文、少数民族名里的「·」、拼音或英文名，
      表里名字后面带的括号备注（如「张三(3班)」）会自动去掉；
    · CSV 表就算是从微信转出来的（GBK 编码）也不会乱码。

  然后做成一张榜：数据管理 → 比赛成绩 → 新建一场比赛
    → 点「把本机录入的成绩并进这场比赛」→ 同步。
    · 榜头会写「共 N 条记录（含 M 条非队员成绩）」，非队员名字旁边有一个灰色「非队员」小标；
    · 名次按成绩快慢排；个人最好成绩榜仍然只统计正式队员。

  想让他们以后进正式名单：数据管理 → 队员名册 → 添加新队员 / 批量添加队员 → 同步即可（成绩不受影响）。
"""
for fn in ('使用说明.txt', 'guide.txt'):
    p = os.path.join(HERE, fn)
    s = io.open(p, encoding='utf-8-sig').read()
    if u'【十三】' in s:
        print(fn, '已写过，跳过')
        continue
    io.open(p, 'w', encoding='utf-8-sig', newline='').write(s.rstrip() + SEC.replace('\n', '\r\n'))
    print(fn, '已追加【十三】')
