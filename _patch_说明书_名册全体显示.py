def apply(path, pairs):
    raw = open(path, 'rb').read()
    bom = raw.startswith(b'\xef\xbb\xbf')
    txt = raw.decode('utf-8-sig')
    crlf = '\r\n' in txt
    txt = txt.replace('\r\n', '\n')
    fails = []
    for i, (old, new) in enumerate(pairs):
        n = txt.count(old)
        if n != 1:
            fails.append((i, n, old.splitlines()[0][:60]))
            continue
        txt = txt.replace(old, new, 1)
    if fails:
        print('❌ %s：' % os.path.basename(path))
        for i, n, s in fails:
            print('   #%d 出现 %d 次: %s' % (i, n, s))
        return False
    data = txt.replace('\n', '\r\n') if crlf else txt
    open(path, 'wb').write((b'\xef\xbb\xbf' if bom else b'') + data.encode('utf-8'))
    print('✅ %s：%d 处替换完成（CRLF=%s BOM=%s）' % (os.path.basename(path), len(pairs), crlf, bom))
    return True


